#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const reportPath = resolve(root, "docs/subscription-tier-p3-recurring-proof-gate-report.md");

const appRepos = [
  ["Verixet", "apps/Verixet"],
  ["XFlow", "apps/XFlow"],
  ["RatAiFy", "apps/RatAiFy"],
  ["AudAiX", "apps/AudAix"],
  ["WordGeni", "apps/WordGeni"],
  ["CreVux", "apps/CreVux"],
];

const focusedProofs = [
  {
    app: "WordGeni",
    path: "apps/WordGeni",
    wrapper: "apps/WordGeni/scripts/verify-subscription-tier-proof.mjs",
    command: "cd apps/WordGeni && node scripts/verify-subscription-tier-proof.mjs",
  },
  {
    app: "CreVux",
    path: "apps/CreVux",
    wrapper: "apps/CreVux/scripts/verify-subscription-tier-proof.mjs",
    command: "cd apps/CreVux && node scripts/verify-subscription-tier-proof.mjs",
  },
  {
    app: "AudAiX",
    path: "apps/AudAix",
    wrapper: "apps/AudAix/scripts/verify-subscription-tier-proof.mjs",
    command: "cd apps/AudAix && node scripts/verify-subscription-tier-proof.mjs",
  },
  {
    app: "RatAiFy",
    path: "apps/RatAiFy",
    wrapper: "apps/RatAiFy/scripts/verify-subscription-tier-proof.mjs",
    command: "cd apps/RatAiFy && node scripts/verify-subscription-tier-proof.mjs",
  },
];

const statusOnlyApps = [
  {
    app: "Verixet",
    path: "apps/Verixet",
    result: "status-only",
    reason:
      "No existing P3 app-level subscription proof wrapper was present. The plan records focused Verixet commands, but this root-only pass does not create app wrappers or invoke package-manager-based checks.",
  },
  {
    app: "XFlow",
    path: "apps/XFlow",
    result: "status-only",
    reason:
      "No existing P3 app-level subscription proof wrapper was present. The plan records focused XFlow commands, but this root-only pass does not create app wrappers or invoke package-manager-based checks.",
  },
];

function run(command, args, cwd) {
  const started = Date.now();
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf8",
    maxBuffer: 1024 * 1024 * 80,
    shell: false,
  });
  const durationMs = Date.now() - started;
  return {
    status: typeof result.status === "number" ? result.status : 1,
    durationMs,
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? (result.error ? String(result.error.message) : ""),
  };
}

function gitStatus(cwd) {
  const result = run("git", ["status", "--short"], cwd);
  if (result.status !== 0) return `ERROR: ${result.stderr.trim() || result.stdout.trim() || `git exited ${result.status}`}`;
  const out = result.stdout.trimEnd();
  return out.length > 0 ? out : "(clean)";
}

function tail(value, maxLines = 28) {
  const normalized = value
    .replace(/\x1b\[[0-9;]*m/g, "")
    .replace(/[^\x09\x0A\x0D\x20-\x7E]/g, "?")
    .trimEnd();
  if (!normalized) return "(none)";
  const lines = normalized.split(/\r?\n/);
  return lines.slice(Math.max(0, lines.length - maxLines)).join("\n");
}

function fenced(value) {
  return ["```text", value, "```"].join("\n");
}

function tableCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", "<br>");
}

const missingWrappers = focusedProofs.filter((proof) => !existsSync(resolve(root, proof.wrapper)));
const proofResults = [];

for (const proof of focusedProofs) {
  if (missingWrappers.some((missing) => missing.app === proof.app)) {
    proofResults.push({
      ...proof,
      status: 1,
      durationMs: 0,
      stdout: "",
      stderr: `Missing wrapper: ${proof.wrapper}`,
    });
    continue;
  }

  const result = run(process.execPath, ["scripts/verify-subscription-tier-proof.mjs"], resolve(root, proof.path));
  proofResults.push({ ...proof, ...result });
}

const rootStatus = gitStatus(root);
const appStatuses = appRepos.map(([app, path]) => ({ app, path, status: gitStatus(resolve(root, path)) }));
const passed = missingWrappers.length === 0 && proofResults.every((result) => result.status === 0);

const lines = [
  "# P3 Recurring Subscription Proof Gate Report",
  "",
  "Date: 2026-07-09",
  "",
  "## Scope",
  "",
  "This report was generated by `node scripts/verify-subscription-tier-p3-gate.mjs`. The verifier is a dependency-free root Node script that runs only app-level focused P3 subscription proof wrappers already committed for WordGeni, CreVux, AudAiX, and RatAiFy.",
  "",
  "The verifier does not run broad CI, all-app test suites, installs, dependency rebuilds, package-manager purges, lockfile rewrites, package upgrades, native rebuilds, migrations, Stripe mutations, checkout flows, entitlement/media/proof-copy behavior changes, app internals, runtime mutations, or CI changes.",
  "",
  "## Gate Result",
  "",
  passed ? "PASS: final P3 recurring subscription proof gate passed." : "FAIL: one or more focused P3 subscription proof wrappers failed.",
  "",
  "## Focused App Proof Results",
  "",
  "| App | Command | Exit code | Duration ms | Result |",
  "| --- | --- | ---: | ---: | --- |",
  ...proofResults.map((result) =>
    `| ${result.app} | \`${result.command}\` | ${result.status} | ${result.durationMs} | ${result.status === 0 ? "passed" : "failed"} |`,
  ),
  ...statusOnlyApps.map((item) => `| ${item.app} | status-only | n/a | n/a | ${item.result} |`),
  "",
  "## Verixet And XFlow Treatment",
  "",
  "| App | Treatment | Reason |",
  "| --- | --- | --- |",
  ...statusOnlyApps.map((item) => `| ${item.app} | ${item.result} | ${tableCell(item.reason)} |`),
  "",
  "## Output Tails",
  "",
  ...proofResults.flatMap((result) => [
    `### ${result.app}`,
    "",
    `Command: \`${result.command}\``,
    "",
    `Exit code: ${result.status}`,
    "",
    "Stdout tail:",
    "",
    fenced(tail(result.stdout)),
    "",
    "Stderr tail:",
    "",
    fenced(tail(result.stderr)),
    "",
  ]),
  "## Git Status Captured By Gate",
  "",
  "Root:",
  "",
  fenced(rootStatus),
  "",
  "| App | Path | Status |",
  "| --- | --- | --- |",
  ...appStatuses.map((item) => `| ${item.app} | \`${item.path}\` | ${item.status === "(clean)" ? "clean" : tableCell(item.status)} |`),
  "",
  "## Remaining Limitations",
  "",
  "- Verixet and XFlow remain status-only in this root verifier because no existing P3 app-level wrapper was present and this pass is root-only.",
  "- Broad app-health suites, route/copy proof, provider proof, staging proof, production proof, Playwright, migrations, and live Stripe/provider checks remain outside this recurring subscription proof gate.",
  "- The baseline report-only script remains available for blocker/status inventory, but this verifier is the recurring focused P3 proof command.",
  "",
  "## Safety Confirmation",
  "",
  "No production code, subscription logic, Stripe logic, checkout flows, entitlement/media/proof-copy behavior, schemas, migrations, broad CI, installs, dependency rebuilds, lockfile churn, package upgrades, native rebuilds, package manifests, CI config, or app internals were changed by this root verifier pass.",
  "",
];

mkdirSync(dirname(reportPath), { recursive: true });
writeFileSync(reportPath, `${lines.join("\n")}\n`, "utf8");

console.log(`${passed ? "PASS" : "FAIL"} P3 subscription proof gate`);
console.log(`Wrote ${reportPath}`);
for (const result of proofResults) {
  console.log(`${result.app}: ${result.status === 0 ? "passed" : "failed"} (${result.durationMs} ms)`);
}
for (const item of statusOnlyApps) {
  console.log(`${item.app}: ${item.result}`);
}

process.exit(passed ? 0 : 1);
